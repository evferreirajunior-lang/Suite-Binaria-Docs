  const languageTag = {
    "pt-br": "pt-BR",
    "en": "en",
    "es": "es",
    "fr": "fr",
    "it": "it"
  };
  const storageKey = "suite-binaria-site-language";
  const buttons = [...document.querySelectorAll("[data-site-lang]")];
  let currentLanguage = "pt-br";

  function translate(key) {
    return dictionary[currentLanguage]?.[key] || dictionary["pt-br"][key] || key;
  }

  function setLanguage(language, persist = true) {
    if (!Object.prototype.hasOwnProperty.call(dictionary, language)) return;
    currentLanguage = language;

    document.documentElement.lang = languageTag[language];
    document.title = translate("pageTitle");
    const description = document.querySelector('meta[name="description"]');
    if (description) description.setAttribute("content", translate("pageDescription"));

    document.querySelectorAll("[data-i18n]").forEach(element => {
      element.textContent = translate(element.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-aria-label]").forEach(element => {
      element.setAttribute("aria-label", translate(element.dataset.i18nAriaLabel));
    });
    buttons.forEach(button => {
      const active = button.dataset.siteLang === language;
      button.classList.toggle("is-active", active);
      button.setAttribute("aria-pressed", String(active));
    });

    if (persist) {
      try { window.localStorage.setItem(storageKey, language); }
      catch (_) { /* Storage may be disabled; switching language still works. */ }
    }

    document.dispatchEvent(new CustomEvent("suite-site-language-change", { detail: { language } }));
  }

  window.SuiteSiteI18n = {
    t: translate,
    language: () => currentLanguage,
    setLanguage
  };

  buttons.forEach(button => {
    button.addEventListener("click", () => setLanguage(button.dataset.siteLang));
  });

  let saved = "pt-br";
  try { saved = window.localStorage.getItem(storageKey) || "pt-br"; }
  catch (_) { /* Keep Portuguese as the default. */ }
  setLanguage(saved, false);
